/// Shown until the user picks a source; the results page hides it as noise.
const FIRST_RUN_STATUS: &str = "Choose a drive or disk image to get started.";
impl Reclaim {
    fn stop_operation(&mut self) {
        self.cancel.store(true, Ordering::Relaxed);
        self.status = "Stopping after the current step…".into();
    }
    fn start(&mut self) {
        let Some(path) = self.source.clone() else {
            return;
        };
        self.results.clear();
        self.inspected = None;
        self.filter.clear();
        self.category = 0;
        self.scan_stopped = false;
        self.scan_error = None;
        self.unreadable.clear();
        self.exporting = false;
        self.started = Some(std::time::Instant::now());
        self.source_stamp = path.metadata().ok().map(|m| (m.len(), m.modified().ok()));
        self.scan_activity = None;
        self.last_scan_update = Some(std::time::Instant::now());
        self.unused_scan = true;
        self.allocation_ready = false;
        self.scanned = 0;
        self.total = 0;
        let drive = self.drives.iter().find(|d| d.path == path);
        let source_size = drive
            .map(|d| d.size)
            .unwrap_or_else(|| path.metadata().map(|m| m.len()).unwrap_or(0));
        self.source_size = (source_size > 0).then_some(source_size);
        self.source_handle = None;
        self.source_alignment = drive.map(|d| d.sector_size).unwrap_or_else(|| {
            if cfg!(target_os = "windows") && path.to_string_lossy().starts_with(r"\\.\") {
                4096
            } else {
                1
            }
        });
        let alignment = self.source_alignment;
        let source_size = self.source_size;
        self.scanned_source = Some(path.clone());
        self.busy = true;
        self.status =
            "Opening source… If Linux asks, authorize read-only access to the drive.".into();
        self.cancel = Arc::new(AtomicBool::new(false));
        let cancel = self.cancel.clone();
        let (tx, rx) = mpsc::sync_channel(256);
        self.receiver = Some(rx);
        std::thread::spawn(move || {
            let result = (|| {
                if cancel.load(Ordering::Relaxed) {
                    return Ok(());
                }
                let handle = Arc::new(drives::open_source(&path)?);
                if cancel.load(Ordering::Relaxed) {
                    return Ok(());
                }
                let mut input =
                    reclaim::SourceReader::new(handle.try_clone()?, alignment, source_size)?;
                tx.send(Message::Opened(handle))
                    .map_err(|_| std::io::Error::other("Window closed"))?;
                let size = source_size.ok_or_else(|| {
                    std::io::Error::other(
                        "The volume size is unknown; unused-space scanning cannot start.",
                    )
                })?;
                reclaim::scan_unused_reader(&mut input, size, &cancel, |e| {
                    // A closed window drops the receiver; stop scanning for it.
                    if tx.send(Message::Scan(e)).is_err() {
                        cancel.store(true, Ordering::Relaxed);
                    }
                })
            })()
            .map_err(|e: std::io::Error| e.to_string());
            // Nobody is waiting for the result once the window has closed.
            tx.send(Message::Done(result)).ok();
        });
    }
    fn visible_result_indices(&self) -> Vec<usize> {
        let query = self.filter.trim().to_lowercase();
        self.results
            .iter()
            .enumerate()
            .filter(|(i, f)| self.shows(*i, f, &query))
            .map(|(i, _)| i)
            .collect()
    }
    /// Whether result `index` passes the category and the (lowercase) search.
    fn shows(&self, index: usize, f: &Found, query: &str) -> bool {
        (self.category == 0 || reclaim::category_index(f.kind) == self.category)
            && (query.is_empty()
                || format!(
                    "{} {} {:x} {}",
                    f.recovery_name(index.saturating_add(1)),
                    f.original_name.as_deref().unwrap_or(""),
                    f.offset,
                    f.offset
                )
                .to_lowercase()
                .contains(query))
    }
    /// Bring the file list model up to date with the least work: rebuild it
    /// only when the filter, category or result list itself changed; otherwise
    /// patch rows whose selection changed and append rows for new results.
    /// Returns the visible and selected row counts.
    fn sync_files(&mut self, ui: &AppWindow) -> (usize, usize) {
        let identity = |f: &Found| (f.offset, f.size, f.kind);
        let last_seen = self
            .shown
            .results_len
            .checked_sub(1)
            .and_then(|index| self.results.get(index))
            .map(identity);
        let files = ui.get_files();
        let model = files.as_any().downcast_ref::<VecModel<FileItem>>();
        // The model must hold exactly the rows recorded here; anything else
        // (another state synced into this window) means start over.
        let rebuild = model.is_none_or(|model| model.row_count() != self.shown.rows.len())
            || self.shown.filter != self.filter
            || self.shown.category != self.category
            || self.shown.results_len > self.results.len()
            || last_seen != self.shown.last;
        if rebuild {
            self.shown.rows.clear();
            self.shown.results_len = 0;
            self.shown.filter.clone_from(&self.filter);
            self.shown.category = self.category;
        } else if let Some(model) = model {
            for (row, (index, selected)) in self.shown.rows.iter_mut().enumerate() {
                if let Some(f) = self.results.get(*index)
                    && f.selected != *selected
                {
                    *selected = f.selected;
                    model.set_row_data(row, file_item(f, *index));
                }
            }
        }
        let query = self.filter.trim().to_lowercase();
        let start = self.shown.results_len;
        let mut added = Vec::new();
        for (index, f) in self.results.iter().enumerate().skip(start) {
            if self.shows(index, f, &query) {
                self.shown.rows.push((index, f.selected));
                added.push(file_item(f, index));
            }
        }
        self.shown.results_len = self.results.len();
        self.shown.last = self.results.last().map(identity);
        match model {
            // Diff in place so the list keeps its scroll position and focus.
            Some(_) if rebuild => replace_model(files.clone(), added, |m| ui.set_files(m)),
            Some(model) => model.extend(added),
            None => ui.set_files(Rc::new(VecModel::from(added)).into()),
        }
        let selected = self.shown.rows.iter().filter(|(_, s)| *s).count();
        (self.shown.rows.len(), selected)
    }
    fn selected_indices(&self) -> Vec<usize> {
        let mut indices = self.visible_result_indices();
        indices.retain(|&index| self.results.get(index).is_some_and(|f| f.selected));
        indices
    }
    fn recovery_files(&self) -> Vec<(Found, usize)> {
        self.selected_indices()
            .into_iter()
            .filter_map(|index| {
                let file = self.results.get(index)?;
                Some((file.clone(), index.saturating_add(1)))
            })
            .collect()
    }
    fn choose_recovery_folder(&mut self) {
        let Some(directory) = rfd::FileDialog::new()
            .set_title(i18n::t("Save to a different physical drive"))
            .pick_folder()
        else {
            return;
        };
        self.review_recovery_folder(directory);
    }
    /// Saves straight away only when the folder provably cannot overwrite the
    /// scanned data; otherwise the destination dialog explains the risk.
    fn review_recovery_folder(&mut self, directory: PathBuf) {
        let Some(source) = &self.scanned_source else {
            return;
        };
        match drives::destination(source, &directory) {
            drives::Destination::Separate => self.export(directory),
            destination => self.recovery_folder = Some((directory, destination)),
        }
    }
    fn export(&mut self, directory: PathBuf) {
        let Some(source) = self.scanned_source.clone() else {
            return;
        };
        let files = self.recovery_files();
        if files.is_empty() {
            return;
        }
        let needs_source_bytes = files.iter().any(|(file, _)| file.resident_data.is_none());
        if needs_source_bytes
            && source.metadata().ok().map(|m| (m.len(), m.modified().ok())) != self.source_stamp
        {
            self.status = "Source changed since scanning. Scan it again before recovering.".into();
            return;
        }
        let Some(handle) = self.source_handle.clone() else {
            self.status = "Scan the selected source before recovering files.".into();
            return;
        };
        let (tx, rx) = mpsc::sync_channel(256);
        self.receiver = Some(rx);
        self.busy = true;
        self.status = "Recovering selected files…".into();
        self.exporting = true;
        self.cancel = Arc::new(AtomicBool::new(false));
        let cancel = self.cancel.clone();
        let alignment = self.source_alignment;
        let source_size = self.source_size;
        std::thread::spawn(move || {
            let result = (|| {
                let input = handle
                    .try_clone()
                    .map_err(|e| format!("Could not read the scanned source: {e}"))?;
                let mut input = reclaim::SourceReader::new(input, alignment, source_size)
                    .map_err(|e| e.to_string())?;
                let mut count = 0usize;
                for (f, number) in files {
                    if cancel.load(Ordering::Relaxed) {
                        return Err(format!("Recovery stopped. {count} files saved."));
                    }
                    reclaim::recover_unique(&mut input, &directory, &f, number)
                        .map_err(|e| format!("Recovered {count} files before error: {e}"))?;
                    count = count.saturating_add(1);
                }
                Ok(count)
            })();
            tx.send(Message::Export(result)).ok();
        });
    }
}
impl Reclaim {
    fn refresh_drives(&mut self) {
        if self.drives_loading || !drives::AVAILABLE {
            return;
        }
        self.drives_loading = true;
        self.drives_error = None;
        if self
            .drive_monitor
            .as_ref()
            .is_some_and(|monitor| monitor.request_refresh())
        {
            return;
        }
        let (tx, rx) = mpsc::channel();
        self.drive_receiver = Some(rx);
        std::thread::spawn(move || {
            tx.send(drives::discover()).ok();
        });
    }
    fn apply_drive_update(&mut self, result: Result<Vec<drives::Drive>, String>) {
        self.drives_loading = false;
        match result {
            Ok(drives) => {
                let was_drive = self
                    .source
                    .as_ref()
                    .is_some_and(|p| self.drives.iter().any(|d| &d.path == p));
                if was_drive && !drives.iter().any(|d| Some(&d.path) == self.source.as_ref()) {
                    self.source = None;
                }
                self.drives = drives;
                self.drives_error = None;
            }
            Err(e) => self.drives_error = Some(e),
        }
    }
    fn poll(&mut self) -> bool {
        let mut changed = false;
        if let Some(result) = self
            .drive_monitor
            .as_mut()
            .and_then(|monitor| monitor.take_update())
        {
            changed = true;
            self.apply_drive_update(result);
        }
        if let Some(result) = self
            .drive_receiver
            .as_ref()
            .and_then(|rx| rx.try_recv().ok())
        {
            self.drive_receiver = None;
            changed = true;
            self.apply_drive_update(result);
        }
        if let Some(rx) = &self.receiver {
            for _ in 0..512 {
                let message = match rx.try_recv() {
                    Ok(message) => message,
                    Err(mpsc::TryRecvError::Empty) => break,
                    Err(mpsc::TryRecvError::Disconnected) => {
                        if self.busy {
                            changed = true;
                            self.busy = false;
                            self.scan_activity = None;
                            if self.exporting {
                                self.exporting = false;
                                self.status = "Recovery ended unexpectedly. Check the destination folder before trying again.".into();
                            } else {
                                self.scan_error = Some("The scan ended unexpectedly. You can recover the files already found or scan again.".into());
                                self.status = "Scan failed. See the message above.".into();
                            }
                        }
                        break;
                    }
                };
                changed = true;
                match message {
                    Message::Opened(handle) => {
                        self.source_handle = Some(handle);
                        self.status = if self.unused_scan {
                            "Reading unused-space map…"
                        } else {
                            "Scanning for recoverable files…"
                        }
                        .into();
                    }
                    Message::Scan(Event::Unreadable { offset, bytes }) => {
                        if let Some((start, length)) = self.unreadable.last_mut()
                            && start.checked_add(*length) == Some(offset)
                        {
                            *length = length.saturating_add(bytes);
                        } else {
                            self.unreadable.push((offset, bytes));
                        }
                    }
                    Message::Scan(Event::UnusedSpace { bytes, .. }) => {
                        self.unused_scan = true;
                        self.allocation_ready = true;
                        self.total = bytes;
                        self.scanned = 0;
                        self.last_scan_update = Some(std::time::Instant::now());
                    }
                    Message::Scan(Event::Found(f)) => self.results.push(f),
                    Message::Scan(Event::Progress(n)) => {
                        if !self.unused_scan || n != self.scanned {
                            self.scan_activity = None;
                        }
                        self.last_scan_update = Some(std::time::Instant::now());
                        self.scanned = n;
                        if !self.cancel.load(Ordering::Relaxed) {
                            self.status = "Scanning for recoverable files…".into();
                        }
                    }
                    Message::Scan(Event::Checking {
                        offset,
                        kind,
                        bytes,
                    }) => {
                        let now = std::time::Instant::now();
                        let since = self
                            .scan_activity
                            .filter(|(at, previous, _, _)| *at == offset && *previous == kind)
                            .map(|(_, _, _, since)| since)
                            .unwrap_or(now);
                        self.scan_activity = Some((offset, kind, bytes, since));
                        self.last_scan_update = Some(now);
                        if !self.unused_scan {
                            self.scanned = self.scanned.max(offset);
                        }
                    }
                    Message::Done(result) => {
                        self.scan_activity = None;
                        self.busy = false;
                        self.scan_stopped = self.cancel.load(Ordering::Relaxed);
                        self.status = match result {
                            Ok(()) if self.cancel.load(Ordering::Relaxed) => {
                                "Scan stopped. You can recover partial results.".into()
                            }
                            Ok(())
                                if self.unused_scan && self.allocation_ready && self.total == 0 =>
                            {
                                "No unused space is available on this volume.".into()
                            }
                            Ok(()) if !self.unreadable.is_empty() => {
                                self.scanned = self.total.max(self.scanned);
                                "Scan finished with unreadable areas. Some files could not be checked. The drive may be failing: recover the files you need now and avoid repeated scans.".into()
                            }
                            Ok(()) => {
                                self.scanned = self.total.max(self.scanned);
                                format!(
                                    "Scan complete. {} file candidates found.",
                                    self.results.len()
                                )
                            }
                            Err(e) => {
                                self.scan_error = Some(i18n::explain(
                                    "Could not read this volume: {0}",
                                    e.clone(),
                                ));
                                "Scan failed. See the message above.".into()
                            }
                        };
                    }
                    Message::Export(result) => {
                        self.busy = false;
                        self.exporting = false;
                        self.status = match result {
                            Ok(n) => format!(
                                "Saved {n} files. Open the destination folder and verify their contents."
                            ),
                            Err(e) => e,
                        };
                    }
                }
            }
        }
        if !self.busy {
            self.receiver = None;
        }
        changed
    }
    fn choose_source(&mut self) {
        if let Some(path) = rfd::FileDialog::new()
            .set_title(i18n::t("Choose a raw disk image"))
            .pick_file()
        {
            self.source = Some(path);
        }
    }
}

fn format_bytes(n: u64) -> String {
    for (unit, divisor) in [
        ("TiB", 1u64 << 40),
        ("GiB", 1 << 30),
        ("MiB", 1 << 20),
        ("KiB", 1 << 10),
    ] {
        if n >= divisor {
            return format!("{:.1} {unit}", n as f64 / divisor as f64);
        }
    }
    format!("{n} B")
}
impl Reclaim {
    /// The status line and the progress beside it. The line stays on one
    /// steady sentence while scanning; it names a check only when that check
    /// is slow, and then keeps it long enough to read.
    fn scan_status(&mut self, now: std::time::Instant) -> (String, String) {
        let scanning = self.busy && !self.cancel.load(Ordering::Relaxed);
        let slow = self
            .scan_activity
            .filter(|_| scanning)
            .filter(|(_, _, _, since)| now.saturating_duration_since(*since) >= LONG_CHECK_AFTER)
            .map(|(_, kind, _, _)| kind);
        self.long_check = match (slow, self.long_check) {
            (Some(kind), Some((shown, at))) if shown == kind => Some((kind, at)),
            (Some(kind), _) => Some((kind, now)),
            (None, Some((kind, at)))
                if scanning && now.saturating_duration_since(at) < LONG_CHECK_SHOWN =>
            {
                Some((kind, at))
            }
            (None, _) => None,
        };
        let status = match self.long_check {
            Some((kind, _)) => i18n::message("Checking a {0} file…", &[&kind.to_uppercase()]),
            None => i18n::t(&self.status),
        };
        let detail = if !self.busy {
            String::new()
        } else if self.total > 0 {
            i18n::message(
                "{0} of {1}",
                &[
                    &format_bytes(self.scanned.min(self.total)),
                    &format_bytes(self.total),
                ],
            )
        } else if self.scanned > 0 {
            i18n::isolate(&format_bytes(self.scanned))
        } else {
            String::new()
        };
        (status, detail)
    }
    fn sync_ui(&mut self, ui: &AppWindow) {
        let (visible, selected) = self.sync_files(ui);
        ui.set_source(
            self.source
                .as_ref()
                .map(|p| i18n::isolate(&p.display().to_string()))
                .unwrap_or_else(|| i18n::t("No source selected"))
                .into(),
        );
        ui.set_busy(self.busy);
        ui.set_drives_refreshing(self.drives_loading);
        ui.set_can_scan(!self.busy && self.source.is_some());
        ui.set_can_recover(!self.busy && selected > 0);
        ui.set_all_selected(visible > 0 && selected == visible);
        ui.set_has_results(!self.results.is_empty());
        ui.set_show_status(
            self.busy
                || self.scan_error.is_some()
                || self.drives_error.is_some()
                || self.status != FIRST_RUN_STATUS,
        );
        let (status, detail) = self.scan_status(std::time::Instant::now());
        ui.set_status(status.into());
        ui.set_scan_detail(detail.into());
        ui.set_error(
            self.scan_error
                .as_ref()
                .or(self.drives_error.as_ref())
                .map(|error| i18n::t(error))
                .unwrap_or_default()
                .into(),
        );
        #[expect(
            clippy::cast_possible_truncation,
            reason = "a ratio clamped to 0..=1 fits f32; only precision is reduced"
        )]
        ui.set_progress(if self.total > 0 {
            (self.scanned as f64 / self.total as f64).clamp(0., 1.) as f32
        } else {
            0.
        });
        ui.set_summary(
            i18n::message(
                "Found: {0} · Selected: {1}",
                &[&self.results.len().to_string(), &selected.to_string()],
            )
            .into(),
        );
        ui.set_detail(
            self.inspected
                .and_then(|index| {
                    self.results
                        .get(index)
                        .map(|file| file_details(file, index.saturating_add(1)))
                })
                .unwrap_or_else(|| i18n::t("Select a file to inspect its details."))
                .into(),
        );
        ui.set_inspected(
            self.inspected
                .filter(|&index| index < self.results.len())
                .and_then(|index| i32::try_from(index).ok())
                .unwrap_or(-1),
        );
        ui.set_preview_error(i18n::t(&ui.get_preview_error_raw()).into());
        ui.set_selected_drive(
            self.drives
                .iter()
                .position(|d| Some(&d.path) == self.source.as_ref())
                .and_then(|n| i32::try_from(n).ok())
                .unwrap_or(-1),
        );
        let drives: Vec<_> = self
            .drives
            .iter()
            .map(|d| DriveItem {
                name: i18n::isolate(&d.display_name()).into(),
                device: device_tag(&d.path).into(),
                icon: drive_icon(d),
                detail: format!(
                    "{} · {}{}",
                    i18n::t(&d.kind),
                    d.location
                        .strip_prefix("Mounted at ")
                        .map(|path| i18n::message("Mounted at {0}", &[path]))
                        .unwrap_or_else(|| i18n::t(&d.location)),
                    if d.encrypted {
                        format!(" · {}", i18n::t("Locked"))
                    } else {
                        String::new()
                    }
                )
                .into(),
                size: format_bytes(d.size).into(),
                available: !d.encrypted,
            })
            .collect();
        replace_model(ui.get_drives(), drives, |m| ui.set_drives(m));
    }
}
/// One row of the file list for result `index`.
fn file_item(f: &Found, index: usize) -> FileItem {
    FileItem {
        name: i18n::isolate(&f.recovery_name(index.saturating_add(1))).into(),
        kind: f.kind.to_uppercase().into(),
        size: format_bytes(f.size).into(),
        selected: f.selected,
        index: i32::try_from(index).unwrap_or(-1),
    }
}
/// Clear the preview and invalidate any preview still loading on a worker.
fn reset_preview(ui: &AppWindow) {
    ui.set_preview(Default::default());
    ui.set_preview_error_raw("".into());
    ui.set_preview_error("".into());
    ui.set_preview_token(ui.get_preview_token().wrapping_add(1));
}
/// Short system name of a drive (`nvme0n1p1`, `disk2s1`, `PhysicalDrive0`, `C:`),
/// shown as a tag beside the human-readable name.
fn device_tag(path: &std::path::Path) -> String {
    let text = path.to_string_lossy();
    let text = text.strip_prefix(r"\\.\").unwrap_or(&text);
    text.rsplit(['/', '\\']).next().unwrap_or(text).to_owned()
}
/// `kind` holds the fixed English labels set by the platform drive discovery.
fn drive_icon(drive: &drives::Drive) -> DriveIcon {
    if drive.encrypted {
        DriveIcon::Locked
    } else if drive.kind == "USB drive" {
        DriveIcon::Usb
    } else if drive.kind == "Entire drive" {
        DriveIcon::Disk
    } else {
        DriveIcon::Volume
    }
}
fn replace_model<T: Clone + PartialEq + 'static>(
    current: ModelRc<T>,
    rows: Vec<T>,
    set: impl FnOnce(ModelRc<T>),
) {
    if let Some(model) = current.as_any().downcast_ref::<VecModel<T>>() {
        // Losing most rows (a new scan, a narrow filter) is one reset, not one
        // notification per removed row.
        if rows.len() < model.row_count() / 2 {
            model.set_vec(rows);
            return;
        }
        while let Some(last) = model.row_count().checked_sub(1)
            && last >= rows.len()
        {
            model.remove(last);
        }
        let existing = model.row_count();
        let mut rows = rows.into_iter();
        for (index, row) in rows.by_ref().take(existing).enumerate() {
            if model.row_data(index).as_ref() != Some(&row) {
                model.set_row_data(index, row);
            }
        }
        // New rows arrive as one batch notification.
        model.extend(rows);
    } else {
        set(Rc::new(VecModel::from(rows)).into());
    }
}
fn file_details(file: &Found, number: usize) -> String {
    let mut lines = vec![
        i18n::isolate(&file.recovery_name(number)),
        format!(
            "{}: {}",
            i18n::t("File type"),
            i18n::isolate(&file.kind.to_uppercase())
        ),
        format!(
            "{}: {} ({} {})",
            i18n::t("Size"),
            i18n::isolate(&format_bytes(file.size)),
            i18n::isolate(&file.size.to_string()),
            i18n::t("bytes")
        ),
        format!(
            "{}: {}",
            i18n::t("Source offset"),
            i18n::isolate(&format!("0x{:X}", file.offset))
        ),
        i18n::t(file.validation.label()),
        i18n::t(if file.original_name.is_some() {
            "Original name recovered"
        } else {
            "Generated filename"
        }),
    ];
    if let Some(metadata) = &file.ntfs {
        lines.push(format!(
            "{}: {} · {}: {}",
            i18n::t("Deleted NTFS record"),
            i18n::isolate(&metadata.record_number.to_string()),
            i18n::t("Sequence"),
            i18n::isolate(&metadata.sequence_number.to_string())
        ));
        for (label, value) in [
            ("Created", metadata.created),
            ("Last modified", metadata.modified),
            ("Record changed", metadata.record_changed),
            ("Last accessed", metadata.accessed),
        ] {
            if let Some(date) =
                value.and_then(|timestamp| chrono::DateTime::from_timestamp(timestamp, 0))
            {
                lines.push(format!(
                    "{}: {}",
                    i18n::t(label),
                    i18n::isolate(&format!("{} UTC", date.format("%Y-%m-%d %H:%M:%S")))
                ));
            }
        }
        lines.push(i18n::t("File dates do not indicate when a file was deleted. This scanner does not recover deletion timestamps."));
    } else {
        lines.push(i18n::t("Deletion not confirmed"));
        lines.push(i18n::t(
            "Dates are not available for files found by signature scanning.",
        ));
    }
    lines.join("\n\n")
}
/// Desktop file ID (`packaging/linux/io.github.reclaim.Reclaim.desktop`). Linux
/// desktops, Wayland ones in particular, take the window icon and taskbar
/// grouping from the `.desktop` file whose name matches the window's app ID.
const APP_ID: &str = "io.github.reclaim.Reclaim";

fn run() -> Result<(), slint::PlatformError> {
    let ui = AppWindow::new()?;
    // After the platform exists (AppWindow::new sets it up) and before the window
    // is shown, which is when it is created. No effect on Windows/macOS.
    slint::set_xdg_app_id(APP_ID)?;
    ui_text::apply(&ui);
    ui.set_language(i18n::preference() as i32);
    {
        let weak = ui.as_weak();
        ui.on_change_language(move |i| {
            if let Some(preference) = usize::try_from(i).ok().and_then(i18n::preference_at) {
                let result = i18n::set_preference(preference);
                if let Some(ui) = weak.upgrade() {
                    ui_text::apply(&ui);
                    if let Err(e) = result {
                        ui.set_error(
                            i18n::message(
                                "Language preference could not be saved: {0}",
                                &[&e.to_string()],
                            )
                            .into(),
                        );
                    }
                }
            }
        });
    }
    ui.on_open_project(|| {
        std::thread::spawn(|| {
            if let Err(e) = installer::open_url("https://github.com/sudo-py-dev/reclaim") {
                diagnostics::write(&e);
            }
        });
    });
    let state = Rc::new(RefCell::new(Reclaim::default()));
    state.borrow_mut().drive_monitor = drives::watch();
    state.borrow_mut().refresh_drives();
    macro_rules! action {
        ($method:ident, $body:expr) => {{
            let state = state.clone();
            let weak = ui.as_weak();
            ui.$method(move || {
                if let Some(ui) = weak.upgrade() {
                    let mut state = state.borrow_mut();
                    ($body)(&mut *state, &ui);
                    state.sync_ui(&ui);
                }
            });
        }};
    }
    // Same as `action!` for callbacks that carry one value from the interface.
    macro_rules! action_with {
        ($method:ident, |$s:ident, $arg:ident: $ty:ty| $body:block) => {{
            let state = state.clone();
            let weak = ui.as_weak();
            ui.$method(move |$arg: $ty| {
                let mut $s = state.borrow_mut();
                $body
                if let Some(ui) = weak.upgrade() {
                    $s.sync_ui(&ui);
                }
            });
        }};
    }
    action!(on_open_image, |s: &mut Reclaim, _: &AppWindow| {
        if !s.busy {
            s.choose_source();
        }
    });
    action!(on_refresh, |s: &mut Reclaim, _: &AppWindow| {
        s.refresh_drives();
    });
    action!(on_scan, |s: &mut Reclaim, ui: &AppWindow| {
        if !s.busy {
            s.start();
            ui.set_page(1);
            ui.set_query("".into());
            ui.set_category(0);
            reset_preview(ui);
        }
    });
    action!(on_stop, |s: &mut Reclaim, _: &AppWindow| {
        s.stop_operation();
    });
    action!(on_filter, |s: &mut Reclaim, ui: &AppWindow| {
        s.filter = ui.get_query().to_string();
        s.category = usize::try_from(ui.get_category()).unwrap_or(0);
    });
    action!(on_recover, |s: &mut Reclaim, _: &AppWindow| {
        if s.busy {
            return;
        }
        s.choose_recovery_folder();
        if let Some((directory, destination)) = s.recovery_folder.take() {
            let explanation = match destination {
                drives::Destination::SameDrive => {
                    "Saving here can overwrite the deleted files you are trying to recover and damage them permanently. Choose a folder on a different physical drive, such as a USB drive."
                }
                _ => {
                    "Saving recovered files to the same physical drive you scanned can overwrite and permanently damage data you are trying to recover. Choose a folder on a different physical drive. Continue only if this destination is on another drive."
                }
            };
            if rfd::MessageDialog::new()
                .set_title(i18n::t("Review recovery destination"))
                .set_description(i18n::t(explanation))
                .set_buttons(rfd::MessageButtons::OkCancel)
                .set_level(rfd::MessageLevel::Warning)
                .show()
                == rfd::MessageDialogResult::Ok
            {
                s.export(directory);
            }
        }
    });
    action_with!(on_select_drive, |s, i: i32| {
        if !s.busy
            && let Ok(i) = usize::try_from(i)
            && let Some(d) = s.drives.get(i).filter(|d| !d.encrypted)
        {
            s.source = Some(d.path.clone());
        }
    });
    action_with!(on_toggle_file, |s, i: i32| {
        if let Ok(i) = usize::try_from(i)
            && let Some(f) = s.results.get_mut(i)
        {
            f.selected = !f.selected;
        }
    });
    action_with!(on_select_all, |s, selected: bool| {
        for i in s.visible_result_indices() {
            if let Some(f) = s.results.get_mut(i) {
                f.selected = selected;
            }
        }
    });
    {
        let state = state.clone();
        let weak = ui.as_weak();
        ui.on_inspect(move |i| {
            // A negative index from the UI means "nothing"; ignore it.
            let Ok(index) = usize::try_from(i) else {
                return;
            };
            let mut s = state.borrow_mut();
            s.inspected = Some(index);
            let Some(f) = s.results.get(index) else {
                return;
            };
            let Some(ui) = weak.upgrade() else {
                return;
            };
            reset_preview(&ui);
            ui.set_detail(file_details(f, index.saturating_add(1)).into());
            ui.set_inspected(i);
            if preview::supported(f.kind) {
                let f = f.clone();
                let handle = s.source_handle.clone();
                let alignment = s.source_alignment;
                let weak = ui.as_weak();
                let token = ui.get_preview_token();
                std::thread::spawn(move || {
                    let result = preview::load(&f, handle, alignment);
                    // Fails only when the event loop has already quit.
                    weak.upgrade_in_event_loop(move |ui| {
                        if ui.get_preview_token() != token {
                            return;
                        }
                        if let Ok(image) = result {
                            let pixels =
                                slint::SharedPixelBuffer::<slint::Rgba8Pixel>::clone_from_slice(
                                    image.as_raw(),
                                    image.width(),
                                    image.height(),
                                );
                            ui.set_preview(slint::Image::from_rgba8(pixels));
                        } else if let Err(error) = result {
                            ui.set_preview_error(i18n::t(&error).into());
                            ui.set_preview_error_raw(error.into());
                        }
                    })
                    .ok();
                });
            }
        });
    }
    let updates = Rc::new(RefCell::new(updates::Updates::new()));
    {
        let updates = updates.clone();
        ui.on_check_update(move || updates.borrow_mut().check());
    }
    {
        let updates = updates.clone();
        ui.on_dismiss_update(move || updates.borrow_mut().dismiss());
    }
    {
        let updates = updates.clone();
        let state = state.clone();
        let weak = ui.as_weak();
        ui.on_apply_update(move || {
            if !state.borrow().busy {
                updates.borrow_mut().apply();
                if updates.borrow().installing()
                    && let Some(ui) = weak.upgrade()
                {
                    ui.set_page(2);
                }
            }
        });
    }
    let timer = slint::Timer::default();
    {
        let state = state.clone();
        let weak = ui.as_weak();
        let last_language = std::cell::Cell::new(i18n::preference());
        let started = std::time::Instant::now();
        let mut last_notes = Vec::new();
        timer.start(
            slint::TimerMode::Repeated,
            Duration::from_millis(100),
            move || {
                if let Some(ui) = weak.upgrade() {
                    let mut s = state.borrow_mut();
                    let changed_language =
                        last_language.replace(i18n::preference()) != i18n::preference();
                    if s.poll() || changed_language {
                        s.sync_ui(&ui);
                    }
                    let mut updates = updates.borrow_mut();
                    if !s.busy && started.elapsed() >= Duration::from_secs(30) {
                        updates.check_automatically();
                    }
                    let was_updating = updates.installing();
                    updates.poll();
                    if was_updating != updates.installing() {
                        s.sync_ui(&ui);
                    }
                    ui.set_update_status(i18n::t(&updates.status).into());
                    if last_notes != updates.notes {
                        replace_model(
                            ui.get_update_notes(),
                            updates
                                .notes
                                .iter()
                                .map(|note| ReleaseNoteBlock {
                                    text: note.text.clone().into(),
                                    kind: note.kind,
                                })
                                .collect(),
                            |model| ui.set_update_notes(model),
                        );
                        last_notes.clone_from(&updates.notes);
                    }
                    ui.set_update_busy(updates.busy());
                    ui.set_update_installing(updates.installing());
                    ui.set_update_notice(updates.notice_visible);
                    ui.set_update_title(updates.title().into());
                    ui.set_update_progress(updates.progress);
                    if updates.installing() {
                        ui.set_can_scan(false);
                        ui.set_can_recover(false);
                    }
                    ui.set_update_available(updates.available());
                    ui.set_update_label(i18n::t(updates.label()).into());
                    if updates.restart {
                        slint::quit_event_loop().ok();
                    }
                }
            },
        );
    }
    // macOS users expect the native traffic-light buttons; elsewhere the app
    // draws its own themed title bar.
    ui.set_custom_frame(!cfg!(target_os = "macos"));
    ui.on_close_window(|| {
        slint::quit_event_loop().ok();
    });
    state.borrow_mut().sync_ui(&ui);
    let result = ui.run();
    state.borrow().cancel.store(true, Ordering::Relaxed);
    result
}
fn main() {
    // The privileged update step runs as root through pkexec, with no desktop
    // session, so it is handled before any GUI, D-Bus or settings setup.
    #[cfg(target_os = "linux")]
    {
        let args: Vec<std::ffi::OsString> = std::env::args_os().skip(1).collect();
        if args
            .first()
            .is_some_and(|a| a == reclaim::updater::INSTALL_DEB_FLAG)
        {
            if let Err(error) = update_runtime::run_privileged_deb_update(&args) {
                // pkexec shows the helper's standard error to the user.
                writeln!(std::io::stderr(), "{error}").ok();
                std::process::exit(1);
            }
            return;
        }
    }
    diagnostics::install();
    i18n::init();
    #[cfg(target_os = "linux")]
    if let Err(error) = native_bus_addresses() {
        diagnostics::report(&i18n::t("A native desktop session is required"), &error);
        std::process::exit(1);
    }
    update_runtime::cleanup_staged_updates();
    if let Err(error) = run() {
        diagnostics::report(&i18n::t("Could not open Reclaim"), &error.to_string());
        std::process::exit(1);
    }
}

